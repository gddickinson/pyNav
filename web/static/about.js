// About: what PyNav is, how to run both apps, privacy, credits (from the README).
import { app, route } from './core.js';

route('about', () => {
  app().innerHTML = `
  <h1>About PyNav</h1>
  <p class="lead">PyNav is a modular GPS navigation program written in Python with PyQt6: GPS tracking (serial NMEA receivers,
    IP geolocation, manual input, and an iPhone companion), route planning with OSRM, GraphHopper or a straight-line offline router,
    tile maps (OpenStreetMap and others) with offline caching, address search and points of interest.</p>
  <h2>This web interface</h2>
  <ul>
    <li><b>Replay</b> reads GPX and NMEA logs and replays them with the app's own maths: haversine distance, bearings, the GPS
      accuracy estimate, the offline router and RoutingEngine's turn-by-turn route following.</li>
    <li>That code now lives in <code>navmath/</code>, a package without Qt that the desktop app imports. The static site runs a
      JavaScript port of it (<code>web/static/nav_engine.js</code>, <code>nmea_engine.js</code>), checked against the Python on
      the same inputs (thousands of values, NMEA and GPX edge cases included).</li>
    <li><b>Live GPS</b> (local app only) reads a serial GPS receiver or the iPhone tracking server.</li>
    <li>Online routing (OSRM/GraphHopper), geocoding and POIs stay in the desktop app: they call external services.</li>
  </ul>
  <h2>Privacy</h2>
  <p>On the static site, files you open are read by JavaScript in your browser and never uploaded. In the local app they go only to
    the server on 127.0.0.1. Map tiles are off unless you switch them on; then images come from tile.openstreetmap.org, which sees the
    area you view. The demo drive is <b>synthetic</b> (generated by <code>scripts/make_demo_track.py</code>), not anyone's movements.</p>
  <h2>Run the desktop app</h2>
  <pre>pip install -r requirements.txt
python main.py</pre>
  <h2>Run the web app</h2>
  <pre>pip install -r requirements-web.txt
python run_web.py        # http://127.0.0.1:8179</pre>
  <h2>Credits</h2>
  <p>By George Dickinson (MIT licence), built with AI assistance from Claude (Anthropic). From the README's acknowledgements:
    OpenStreetMap (map data and tiles, © OpenStreetMap contributors), the OSRM project (routing), Nominatim (geocoding), PyQt6.
    NMEA parsing in Python uses pynmea2.</p>`;
});
